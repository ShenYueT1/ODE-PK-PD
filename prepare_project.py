from pathlib import Path
import json, re, shutil
root = Path(__file__).resolve().parent.parent
project = root / 'outputs' / 'kinetica'
sdk = Path('C:/flutter')
template = sdk / 'packages/flutter_tools/templates/app/windows.tmpl'
for source in template.rglob('*'):
    if not source.is_file():
        continue
    rel = str(source.relative_to(template)).replace('.img.tmpl','').replace('.tmpl','')
    target = project / 'windows' / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    if source.name.endswith('.img.tmpl'):
        shutil.copyfile(source, target)
    else:
        body = source.read_text(encoding='utf-8')
        body = re.sub(r'{{#withPlatformChannelPluginHook}}.*?{{/withPlatformChannelPluginHook}}', '', body, flags=re.S)
        for key,value in {'projectName':'kinetica','organization':'dev.kinetica','year':'2026'}.items():
            body = body.replace('{{'+key+'}}', value)
        body = body.replace('Size size(1280, 720)', 'Size size(1600, 1000)').replace('L"kinetica"', 'L"Kinetica - PK/PD Studio"')
        target.write_text(body, encoding='utf-8')
(project / 'windows/flutter/generated_plugins.cmake').write_text('# No native plugins. Regenerated by Flutter.\n', encoding='utf-8')
(project / 'windows/flutter/generated_plugin_registrant.h').write_text('#ifndef GENERATED_PLUGIN_REGISTRANT_\n#define GENERATED_PLUGIN_REGISTRANT_\n#include <flutter/plugin_registry.h>\nvoid RegisterPlugins(flutter::PluginRegistry* registry);\n#endif\n', encoding='utf-8')
(project / 'windows/flutter/generated_plugin_registrant.cc').write_text('#include "generated_plugin_registrant.h"\nvoid RegisterPlugins(flutter::PluginRegistry* registry) {}\n', encoding='utf-8')
source_config = sdk / 'packages/flutter_tools/.dart_tool/package_config.json'
packages = json.loads(source_config.read_text())
for package in packages['packages']:
    if not package['rootUri'].startswith('file:'):
        package['rootUri'] = (source_config.parent / package['rootUri']).resolve().as_uri() + '/'
for name, directory in [('flutter',sdk/'packages/flutter'),('flutter_test',sdk/'packages/flutter_test'),('sky_engine',sdk/'bin/cache/pkg/sky_engine'),('kinetica',project)]:
    packages['packages'] = [p for p in packages['packages'] if p['name'] != name]
    packages['packages'].append({'name':name, 'rootUri':directory.as_uri()+'/', 'packageUri':'lib/', 'languageVersion':'3.9'})
cache = Path('C:/Users/Hans/AppData/Local/Pub/Cache/hosted/pub.dev')
for name in ['characters','collection','material_color_utilities','vector_math','leak_tracker_flutter_testing','leak_tracker','leak_tracker_testing']:
    if any(p['name']==name for p in packages['packages']):
        continue
    candidates = sorted(cache.glob(name+'-*'))
    if candidates:
        packages['packages'].append({'name':name,'rootUri':candidates[-1].as_uri()+'/', 'packageUri':'lib/', 'languageVersion':'3.7'})
(project/'.dart_tool').mkdir(exist_ok=True)
(project/'.dart_tool/package_config.json').write_text(json.dumps(packages,indent=2))
print('Prepared Windows runner and local analysis package map.')
